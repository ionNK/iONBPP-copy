'use client';

import { useMemo, useState } from 'react';
import { Check } from 'lucide-react';
import { GhostButton, PrimaryButton } from '@/components/ui';
import { MARKETS } from '@/lib/bulk-upload/markets';
import { parseCsv } from '@/lib/bulk-upload/parseCsv';
import { autoMap, applyOverrides, fieldDef } from '@/lib/bulk-upload/columnMap';
import type { MappingOverrides } from '@/lib/bulk-upload/columnMap';
import { validateCsv } from '@/lib/bulk-upload/validate';
import type { ValidationResult } from '@/lib/bulk-upload/validate';
import { submitBatch } from '@/lib/bulk-upload/mockBatches';
import type { Batch, SubmitInput } from '@/lib/bulk-upload/mockBatches';
import { BulkUploadDetails, DEFAULT_DETAILS, detailsComplete, resolveExpiry, resolveTerms } from './BulkUploadDetails';
import type { DetailsState } from './BulkUploadDetails';
import { BulkUploadDropzone } from './BulkUploadDropzone';
import type { SelectedFile } from './BulkUploadDropzone';
import { BulkUploadMapping } from './BulkUploadMapping';
import { BulkUploadPreview } from './BulkUploadPreview';
import { BulkUploadSummary } from './BulkUploadSummary';
import { BulkUploadResult } from './BulkUploadResult';

const STEPS = ['Details', 'Upload', 'Validate', 'Review', 'Result'] as const;
type StepIndex = 1 | 2 | 3 | 4 | 5;
/** Sub-step 2b ("Map columns") sits between Upload and Validate and is only visited when auto-mapping falls short. */
type Step = StepIndex | '2b';

const stepIndex = (s: Step): StepIndex => (s === '2b' ? 2 : s);

const fileErrorMessage = (result: ValidationResult | null): string | null => {
  if (!result?.fileError) return null;
  if (result.fileError.fileError === 'empty_file') return 'The file is empty — it needs a header row.';
  const labels = result.fileError.unmapped.map((f) => fieldDef(f).label);
  return `Could not find a column for ${labels.join(' and ')}. Continue to map the file's columns manually.`;
};

/** DetailsState → the batch details persisted with the submission (recipients CSV is generated by the store). */
const toBatchDetails = (d: DetailsState): SubmitInput['details'] => ({
  name: d.name.trim(),
  reference: d.reference.trim(),
  market: d.market,
  currency: MARKETS[d.market].currency,
  awardType: d.awardType,
  expiry: d.awardType === 'cash' ? null : (resolveExpiry(d) ?? { mode: 'relative', value: 7, unit: 'days' }),
  terms: resolveTerms(d),
  sms: { message: d.smsMessage.trim(), method: d.smsMethod, owner: d.smsMethod === 'manual' ? d.smsOwner.trim() : undefined },
  description: d.description.trim() || undefined,
});

export interface BulkUploadStepperProps {
  /** Fired after a batch is stored (awarded or pending approval). */
  onSubmitted?: (batch: Batch) => void;
  onViewHistory?: (batch: Batch) => void;
}

/**
 * Bulk FreeBet Upload stepper (PROTOTYPE, mock data). Five steps: Details →
 * Upload → Validate → Review → Result. The upload IS the campaign: no promo
 * config is selected; winners and amounts are pre-determined offline.
 * Presentation is CSS-only (.bulk-upload block in app/design-system.css);
 * the single permitted inline style is the progress bar width.
 */
export function BulkUploadStepper({ onSubmitted, onViewHistory }: BulkUploadStepperProps) {
  const [step, setStep] = useState<Step>(1);
  const [details, setDetails] = useState<DetailsState>(DEFAULT_DETAILS);
  const [file, setFile] = useState<SelectedFile | null>(null);
  const [overrides, setOverrides] = useState<MappingOverrides>({});
  const [batch, setBatch] = useState<Batch | null>(null);

  const market = MARKETS[details.market];

  /* Parsed once per file; mapping overrides are per-upload, so a new file clears them. */
  const parsed = useMemo(() => (file ? parseCsv(file.text) : null), [file]);
  const auto = useMemo(() => (parsed ? autoMap(parsed.headers) : null), [parsed]);
  const effective = useMemo(() => (auto ? applyOverrides(auto, overrides) : null), [auto, overrides]);

  /* Re-validates whenever the file, mapping or market changes (market drives MSISDN normalisation + currency). */
  const result = useMemo<ValidationResult | null>(
    () => (parsed ? validateCsv(parsed, market, overrides) : null),
    [parsed, market, overrides],
  );
  const needsMapping = result?.fileError?.fileError === 'unmapped_fields';
  const fileError = fileErrorMessage(result);
  const submittable = result ? result.summary.valid + result.summary.warning : 0;

  const canAdvance: Record<Step, boolean> = {
    1: detailsComplete(details),
    /* Upload advances when the file parsed and is either fully mapped or mappable on 2b. */
    2: file !== null && result !== null && (!result.fileError || needsMapping === true),
    '2b': result !== null && !result.fileError,
    3: result !== null && !result.fileError,
    4: submittable > 0,
    5: false,
  };

  const selectFile = (f: SelectedFile) => { setFile(f); setOverrides({}); };
  const clearFile = () => { setFile(null); setOverrides({}); };

  const next = () => setStep((s) => {
    if (s === 2) return needsMapping ? '2b' : 3;
    if (s === '2b') return 3;
    return s < 5 ? ((s + 1) as StepIndex) : s;
  });
  const back = () => setStep((s) => {
    if (s === '2b') return 2;
    if (s === 3) return Object.keys(overrides).length > 0 ? '2b' : 2;
    return s > 1 ? ((s - 1) as StepIndex) : s;
  });

  const confirm = () => {
    if (!result || submittable === 0) return;
    const stored = submitBatch({ details: toBatchDetails(details), headers: result.headers, rows: result.rows, totalUnits: result.summary.totalUnits });
    setBatch(stored);
    setStep(5);
    onSubmitted?.(stored);
  };

  const reset = () => {
    setStep(1);
    setDetails(DEFAULT_DETAILS);
    setFile(null);
    setOverrides({});
    setBatch(null);
  };

  const current = stepIndex(step);
  const progress = ((current - 1) / (STEPS.length - 1)) * 100;
  const caption = step === '2b' ? 'Step 2 of 5 · Map columns' : `Step ${current} of ${STEPS.length} · ${STEPS[current - 1]}`;

  return (
    <section className="bulk-upload" aria-labelledby="bulk-upload-title" data-testid="bulk-upload-stepper">
      <div className="bulk-upload__head">
        <div>
          <h2 id="bulk-upload-title" className="bulk-upload__section-title">Bulk award upload</h2>
          <p className="bulk-upload__caption" data-testid="bulk-caption">{caption}</p>
        </div>
      </div>

      <ol className="bulk-upload__steps" aria-label="Bulk upload progress">
        {STEPS.map((label, i) => {
          const n = (i + 1) as StepIndex;
          const state = n < current ? 'done' : n === current ? 'current' : 'todo';
          return (
            <li
              key={label}
              className={`bulk-upload__step bulk-upload__step--${state}`}
              data-testid={`bulk-step-${n}`}
              data-state={state}
              aria-current={n === current ? 'step' : undefined}
            >
              <span className="bulk-upload__step-circle" aria-hidden="true">{state === 'done' ? <Check size={14} /> : n}</span>
              <span className="bulk-upload__step-label">{label}</span>
            </li>
          );
        })}
      </ol>
      <div
        className="bulk-upload__progress"
        role="progressbar"
        aria-valuemin={0}
        aria-valuemax={100}
        aria-valuenow={Math.round(progress)}
        aria-label="Bulk upload progress"
      >
        {/* Sole permitted inline style: progress bar width. */}
        <span className="bulk-upload__progress-fill" style={{ width: `${progress}%` }} />
      </div>

      <div className="bulk-upload__body" data-testid={`bulk-panel-${step}`}>
        {step === 1 && <BulkUploadDetails value={details} onChange={setDetails} />}
        {step === 2 && (
          <BulkUploadDropzone
            file={file}
            onFile={selectFile}
            onClear={clearFile}
            fileError={fileError}
            fileErrorTone={needsMapping ? 'info' : 'error'}
            fileWarnings={result?.fileWarnings}
          />
        )}
        {step === '2b' && parsed && effective && (
          <BulkUploadMapping
            headers={parsed.headers}
            mapping={effective.mapping}
            unmapped={effective.unmapped}
            overrides={overrides}
            onChange={setOverrides}
          />
        )}
        {step === 3 && result && <BulkUploadPreview result={result} />}
        {step === 4 && result && <BulkUploadSummary details={toBatchDetails(details)} summary={result.summary} />}
        {step === 5 && batch && (
          <BulkUploadResult
            batch={batch}
            onViewHistory={onViewHistory ? () => onViewHistory(batch) : undefined}
            onStartAnother={reset}
          />
        )}
      </div>

      {step !== 5 && (
        <div className="bulk-upload__footer">
          <span data-testid="bulk-back">{step !== 1 ? <GhostButton onClick={back}>Back</GhostButton> : null}</span>
          {step !== 4 ? (
            <span data-testid="bulk-next">
              <PrimaryButton onClick={next} disabled={!canAdvance[step]}>{step === '2b' ? 'Continue' : 'Next'}</PrimaryButton>
            </span>
          ) : (
            <span data-testid="bulk-confirm">
              <PrimaryButton onClick={confirm} disabled={!canAdvance[4]}>Confirm and submit</PrimaryButton>
            </span>
          )}
        </div>
      )}
    </section>
  );
}

export default BulkUploadStepper;
